create extension if not exists btree_gist;

-- Booking rules (mirrored for display in store.js; the database is the authority)
--   Open 10:00, close 21:00 (Africa/Accra), sessions 1–4 hours,
--   engineer add-on GH₵100/hour, bookings up to 90 days ahead.

-- -------------------------------------------------------------
-- Profiles (one per auth user)
-- -------------------------------------------------------------
create table public.profiles (
    id          uuid primary key references auth.users (id) on delete cascade,
    name        text not null default '' check (char_length(name) <= 60),
    email       text not null,
    is_admin    boolean not null default false,
    created_at  timestamptz not null default now()
);

create function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
    insert into public.profiles (id, name, email)
    values (
        new.id,
        left(coalesce(trim(new.raw_user_meta_data ->> 'name'), ''), 60),
        lower(new.email)
    );
    return new;
end;
$$;

create trigger on_auth_user_created
    after insert on auth.users
    for each row execute function public.handle_new_user();

create function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select coalesce((select p.is_admin from public.profiles p where p.id = auth.uid()), false);
$$;

