-- -------------------------------------------------------------
-- Bookings
-- -------------------------------------------------------------
create table public.bookings (
    id              uuid primary key default gen_random_uuid(),
    ref             text not null unique,
    user_id         uuid not null references auth.users (id) on delete cascade,
    user_name       text not null check (char_length(user_name) between 1 and 60),
    user_email      text not null,
    phone           text not null check (phone ~ '^\+?[0-9\s-]{9,16}$'),
    studio_id       text references public.studios (id) on delete set null,
    studio_name     text not null,
    session_type    text not null check (session_type in (
                        'Recording Session', 'Mixing & Mastering', 'Beat Production',
                        'Podcast / Voice-Over', 'Band Rehearsal')),
    date            date not null,
    start_hour      int not null check (start_hour between 10 and 20),
    hours           int not null check (hours between 1 and 4),
    engineer        boolean not null default false,
    amount          numeric(10, 2) not null check (amount >= 0),
    currency        text not null default 'GHS',
    status          text not null default 'Pending'
                        check (status in ('Pending', 'Approved', 'Completed', 'Rejected', 'Cancelled')),
    payment_status  text not null check (payment_status in ('paid', 'demo')),
    payment_ref     text unique,
    notes           text not null default '' check (char_length(notes) <= 500),
    created_at      timestamptz not null default now(),
    constraint bookings_within_hours check (start_hour + hours <= 21),
    -- The real double-booking guard: active bookings for a studio can't overlap
    constraint bookings_no_overlap exclude using gist (
        studio_id with =,
        date with =,
        int4range(start_hour, start_hour + hours) with &&
    ) where (status in ('Pending', 'Approved', 'Completed'))
);

create index bookings_user_idx on public.bookings (user_id);
create index bookings_date_idx on public.bookings (date);

-- Payments that succeeded but couldn't become a booking (slot taken in a race).
-- Admins follow these up for a refund.
create table public.payment_issues (
    id           bigint generated by default as identity primary key,
    user_id      uuid references auth.users (id) on delete set null,
    payment_ref  text not null,
    amount       numeric(10, 2),
    reason       text not null,
    payload      jsonb not null default '{}'::jsonb,
    resolved     boolean not null default false,
    created_at   timestamptz not null default now()
);

