-- Hours taken on a date (active bookings + studio blocks). Public:
-- exposes only hour numbers, never who booked.
create function public.get_booked_hours(p_studio_id text, p_date date)
returns int[]
language sql
stable
security definer
set search_path = ''
as $$
    select coalesce(array_agg(distinct h order by h), '{}')
    from (
        select generate_series(b.start_hour, b.start_hour + b.hours - 1) as h
        from public.bookings b
        where b.studio_id = p_studio_id
          and b.date = p_date
          and b.status in ('Pending', 'Approved', 'Completed')
        union
        select split_part(slot, ':', 1)::int
        from public.studios s,
             jsonb_array_elements_text(coalesce(s.unavailable_slots -> to_char(p_date, 'YYYY-MM-DD'), '[]'::jsonb)) as slot
        where s.id = p_studio_id
    ) taken;
$$;

-- Validate a proposed session and return the authoritative price.
create function public.quote_booking(
    p_studio_id  text,
    p_date       date,
    p_start_hour int,
    p_hours      int,
    p_engineer   boolean default false
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
    v_studio public.studios;
    v_now    timestamp := now() at time zone 'Africa/Accra';
    v_taken  int[];
begin
    select * into v_studio from public.studios where id = p_studio_id;
    if v_studio.id is null then
        return jsonb_build_object('ok', false, 'error', 'Studio not found.');
    end if;
    if p_hours is null or p_hours < 1 or p_hours > 4 then
        return jsonb_build_object('ok', false, 'error', 'Sessions can be 1–4 hours.');
    end if;
    if p_start_hour is null or p_start_hour < 10 or p_start_hour + p_hours > 21 then
        return jsonb_build_object('ok', false, 'error', 'Sessions must be between 10:00 and 21:00.');
    end if;
    if p_date is null or p_date < v_now::date
       or (p_date = v_now::date and p_start_hour <= extract(hour from v_now)) then
        return jsonb_build_object('ok', false, 'error', 'That time has already passed.');
    end if;
    if p_date > v_now::date + 90 then
        return jsonb_build_object('ok', false, 'error', 'Bookings open up to 90 days ahead.');
    end if;

    v_taken := public.get_booked_hours(p_studio_id, p_date);
    if v_taken && array(select generate_series(p_start_hour, p_start_hour + p_hours - 1)) then
        return jsonb_build_object('ok', false, 'error', 'That time slot is no longer available. Please pick another.');
    end if;

    return jsonb_build_object(
        'ok', true,
        'studio_name', v_studio.name,
        'amount', v_studio.hourly_rate * p_hours + (case when p_engineer then 100 * p_hours else 0 end),
        'currency', 'GHS'
    );
end;
$$;

-- Create a booking. Only the `book` Edge Function (service role) may call
-- this, after it has verified the payment.
create function public.create_booking(
    p_user_id        uuid,
    p_studio_id      text,
    p_session_type   text,
    p_date           date,
    p_start_hour     int,
    p_hours          int,
    p_engineer       boolean,
    p_user_name      text,
    p_phone          text,
    p_notes          text,
    p_ref            text,
    p_payment_ref    text,
    p_payment_status text,
    p_amount_paid    numeric
)
returns public.bookings
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_quote   jsonb;
    v_profile public.profiles;
    v_row     public.bookings;
begin
    select * into v_profile from public.profiles where id = p_user_id;
    if v_profile.id is null then
        raise exception 'Unknown user.' using errcode = 'P0001';
    end if;

    v_quote := public.quote_booking(p_studio_id, p_date, p_start_hour, p_hours, p_engineer);
    if not (v_quote ->> 'ok')::boolean then
        raise exception '%', v_quote ->> 'error' using errcode = 'P0001';
    end if;
    if p_payment_status = 'paid' and p_amount_paid < (v_quote ->> 'amount')::numeric then
        raise exception 'Amount paid does not match the session price.' using errcode = 'P0001';
    end if;

    insert into public.bookings (
        ref, user_id, user_name, user_email, phone, studio_id, studio_name, session_type,
        date, start_hour, hours, engineer, amount, currency, status, payment_status, payment_ref, notes
    ) values (
        p_ref, p_user_id,
        left(coalesce(nullif(trim(p_user_name), ''), v_profile.name), 60),
        v_profile.email, trim(p_phone), p_studio_id, v_quote ->> 'studio_name', p_session_type,
        p_date, p_start_hour, p_hours, coalesce(p_engineer, false),
        (v_quote ->> 'amount')::numeric, 'GHS', 'Pending', p_payment_status, p_payment_ref,
        left(coalesce(p_notes, ''), 500)
    )
    returning * into v_row;
    return v_row;
end;
$$;

-- Clients cancel their own active, upcoming bookings
create function public.cancel_booking(p_id uuid)
returns public.bookings
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_row public.bookings;
begin
    update public.bookings
       set status = 'Cancelled'
     where id = p_id
       and user_id = auth.uid()
       and status in ('Pending', 'Approved')
       and date >= (now() at time zone 'Africa/Accra')::date
    returning * into v_row;
    if v_row.id is null then
        raise exception 'This booking can no longer be cancelled.' using errcode = 'P0001';
    end if;
    return v_row;
end;
$$;

-- Featured client reviews for the public testimonials carousel
create function public.get_featured_reviews()
returns table (name text, stars int, text text)
language sql
stable
security definer
set search_path = ''
as $$
    select coalesce(nullif(f.name, ''), split_part(f.user_email, '@', 1)), f.rating, f.message
    from public.feedbacks f
    where f.featured
    order by f.created_at;
$$;

