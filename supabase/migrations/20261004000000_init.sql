    featured     boolean not null default false,
    created_at   timestamptz not null default now()
);

-- Fill trusted fields server-side so clients can't spoof them
create function public.feedback_before_insert()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_profile public.profiles;
    v_studio  public.studios;
begin
    select * into v_profile from public.profiles where id = new.user_id;
    select * into v_studio from public.studios where id = new.studio_id;
    if v_studio.id is null then
        raise exception 'Please choose a studio.' using errcode = 'P0001';
    end if;
    new.user_email  := coalesce(v_profile.email, '');
    new.name        := coalesce(nullif(trim(new.name), ''), v_profile.name, '');
    new.studio_name := v_studio.name;
    new.message     := trim(new.message);
    if not public.is_admin() then
        new.featured := false;
    end if;
    return new;
end;
$$;

create trigger feedback_before_insert
    before insert on public.feedbacks
    for each row execute function public.feedback_before_insert();

